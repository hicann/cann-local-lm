import json
from pathlib import Path

import torch

# 检测 NPU 可用性
try:
    import torch_npu  # noqa: F401

    _HAS_NPU = True
except ImportError:
    _HAS_NPU = False


def resolve_device(device: str) -> torch.device:
    """解析设备字符串

    Args:
        device: 设备字符串 ("auto", "cpu", "npu")

    Returns:
        torch.device 实例
    """
    if device == "auto":
        if _HAS_NPU and torch.npu.is_available():
            return torch.device("npu")
        else:
            return torch.device("cpu")

    resolved = torch.device(device)
    if resolved.type == "npu":
        if not (_HAS_NPU and torch.npu.is_available()):
            raise RuntimeError("NPU was requested but torch_npu is not available")
    return resolved


def create_test_inputs(
    model_name: str, device: torch.device, dtype: torch.dtype
) -> tuple:
    """创建测试输入数据

    使用固定种子确保跨进程数据一致。

    Args:
        model_name: 模型名称 ("simple", "chain", "param")
        device: 设备
        dtype: 数据类型

    Returns:
        输入 tensor tuple
    """
    torch.manual_seed(42)  # 固定种子

    input_shapes = {
        "simple": [(4, 4), (4, 4)],
        "chain": [(4, 4)],
        "param": [(4, 4)],
    }

    if model_name not in input_shapes:
        raise ValueError(f"Unknown model: {model_name}")

    shapes = input_shapes[model_name]
    inputs = tuple(
        torch.randn(*shape, device=device, dtype=dtype, requires_grad=False)
        for shape in shapes
    )
    return inputs


def save_fx_graph(graph, output_path: Path, method: str, model_name: str):
    """保存 FX 图结构到文件

    Args:
        graph: FX Graph 对象
        output_path: 输出文件路径
        method: 产生方式 ("export", "dynamo", "aoti", "epair")
        model_name: 模型名称
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w") as f:
        f.write(f"=== FX Graph: {method} (model={model_name}) ===\n")
        f.write(f"Nodes: {len(graph.nodes)}\n\n")

        for node in graph.nodes:
            inplace_marker = ""

            # 检测 inplace 操作的多种模式
            if node.op == "call_function":
                target_str = str(node.target)
                # 模式1: aten.xxx_.Tensor (torch.export 格式)
                # 模式2: aten.xxx_.default (Inductor copy_ 格式)
                if "_.Tensor" in target_str or "_.default" in target_str:
                    inplace_marker = "  >>> INPLACE OPERATION <<<"

            elif node.op == "call_method":
                target_str = str(node.target)
                # 模式3: 方法名以 _ 结尾 (Dynamo 捕获的 Python 方法)
                # 如: add_, mul_, div_, copy_, etc.
                if target_str.endswith("_") and not target_str.endswith("__"):
                    inplace_marker = "  >>> INPLACE OPERATION <<<"

            f.write(f"[{node.op}] {node.name}\n")
            f.write(f"  target: {node.target}{inplace_marker}\n")

            if node.op in ("call_function", "call_method"):
                args_str = []
                for arg in node.args:
                    if hasattr(arg, "name"):
                        args_str.append(arg.name)
                    else:
                        args_str.append(str(arg))
                f.write(f"  args: ({', '.join(args_str)})\n")

            f.write("\n")

    print(f"  Saved FX graph to: {output_path}")


def save_fx_code(code: str, output_path: Path, method: str, model_name: str):
    """保存 FX 图代码到文件

    Args:
        code: FX 图生成的代码
        output_path: 输出文件路径
        method: 产生方式
        model_name: 模型名称
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w") as f:
        f.write(f"# FX Graph Code: {method} (model={model_name})\n")
        f.write("# Auto-generated by torch.export / torch.compile\n\n")
        f.write(code)

    print(f"  Saved FX code to: {output_path}")


def verify_inplace_modification(
    name: str,
    original_inputs: tuple,
    inputs_after_run: tuple,
    eager_inputs_after: tuple,
    tolerance: float = 1e-5,
) -> bool:
    """验证 inplace 修改是否正确

    Args:
        name: 测试名称
        original_inputs: 运行前的原始输入
        inputs_after_run: 编译模型运行后的输入
        eager_inputs_after: eager 模式运行后的输入（参考）
        tolerance: 精度容忍度

    Returns:
        是否验证通过
    """
    print(f"\n[{name}] Inplace Verification:")

    all_passed = True
    for i, (original, after_run, eager_after) in enumerate(
        zip(original_inputs, inputs_after_run, eager_inputs_after)
    ):
        is_modified = not torch.equal(original, after_run)
        print(f"  Input[{i}] modified: {is_modified}")

        diff = (after_run - eager_after).abs().max().item()
        print(f"  Input[{i}] max diff from eager: {diff:.6e}")

        if diff < tolerance:
            print(f"  Input[{i}] [PASS] Inplace modification matches eager")
        else:
            print(f"  Input[{i}] [FAIL] Inplace modification differs from eager")
            all_passed = False

    return all_passed


def compare_outputs(name: str, output, eager_output, tolerance: float = 1e-5) -> bool:
    """对比输出精度

    Args:
        name: 测试名称
        output: 编译模型输出
        eager_output: eager 模式输出（参考）
        tolerance: 精度容忍度

    Returns:
        是否验证通过
    """
    print(f"\n[{name}] Output Comparison:")

    if isinstance(output, torch.Tensor) and isinstance(eager_output, torch.Tensor):
        diff = (output - eager_output).abs().max().item()
        print(f"  Output max diff: {diff:.6e}")

        if diff < tolerance:
            print("  [PASS] Output matches eager")
            return True
        else:
            print("  [FAIL] Output differs from eager")
            return False

    elif isinstance(output, (tuple, list)) and isinstance(eager_output, (tuple, list)):
        all_passed = True
        for i, (o, e) in enumerate(zip(output, eager_output)):
            if isinstance(o, torch.Tensor) and isinstance(e, torch.Tensor):
                diff = (o - e).abs().max().item()
                print(f"  Output[{i}] max diff: {diff:.6e}")

                if diff >= tolerance:
                    all_passed = False

        if all_passed:
            print("  [PASS] All outputs match eager")
        else:
            print("  [FAIL] Some outputs differ from eager")
        return all_passed

    else:
        print("  [ERROR] Output types mismatch")
        return False


def save_manifest(manifest, output_path: Path, model_name: str):
    """保存 epair manifest 信息

    Args:
        manifest: EpairManifest 对象
        output_path: 输出文件路径
        model_name: 模型名称
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)

    manifest_dict = {
        "model": model_name,
        "version": manifest.version,
        "backend_name": manifest.backend_name,
        "cann_version": manifest.cann_version,
        "total_nodes": manifest.total_nodes,
        "converted_nodes": manifest.converted_nodes,
    }

    with open(output_path, "w") as f:
        json.dump(manifest_dict, f, indent=2)

    print(f"  Saved manifest to: {output_path}")
    print(f"  Converted: {manifest.converted_nodes}/{manifest.total_nodes} nodes")
