"""Tests for cann_local_lm._token_count — lightweight stdlib BPE token counter.

Exact encode vs the bpe_fixture golden (SentencePiece-style byte-fallback BPE);
conservative len(text) fallback for unsupported layouts (Qwen/ByteLevel/SPM/
missing file). No third-party imports — pure stdlib json/re.
"""

import json
import os

import pytest

from cann_local_lm._token_count import count_tokens, encode, TokenizeUnsupported

FIX_DIR = os.path.normpath(
    os.path.join(os.path.dirname(__file__), "..", "cpp", "engine")
)
BPE_TOK = os.path.join(FIX_DIR, "bpe_fixture_tokenizer.json")
BPE_GOLDEN = os.path.join(FIX_DIR, "bpe_fixture_golden.json")
QWEN_TOK = os.path.join(FIX_DIR, "qwen_fixture_tokenizer.json")

# bpe_fixture 是 gitignored 生成物(.gitignore: fixtures/),由
# tests/cpp/engine/gen_fixture.py 用 HF `tokenizers` 库生成。
# conftest 会在 pytest 开跑前尝试自动生成(有该库时);无该库的环境下不生成,
# 这批精确比对用例跳过——TestFallback 的缺失文件用例不依赖真 fixture,仍跑。
needs_bpe_fixture = pytest.mark.skipif(
    not (os.path.isfile(BPE_TOK) and os.path.isfile(BPE_GOLDEN)),
    reason="bpe_fixture tokenizer/golden missing — generated by "
    "tests/cpp/engine/gen_fixture.py (needs HF `tokenizers`)",
)


def _golden_cases():
    with open(BPE_GOLDEN, encoding="utf-8") as f:
        return json.load(f)["cases"]


@needs_bpe_fixture
class TestBpeExactAgainstGolden:
    """count_tokens / encode must match the engine's tokenizer exactly for the
    bpe_fixture layout (SentencePiece byte-fallback BPE: Replace(' '->'▁')
    normalizer + Split(' ', MergedWithPrevious) pre-tokenizer + BPE merges +
    byte fallback + added-token pre-split)."""

    def test_count_matches_golden_for_all_cases(self):
        # one assertion per case so a failure names the offending input
        for c in _golden_cases():
            got = count_tokens(c["text"], BPE_TOK)
            assert got == len(c["ids"]), (
                f"text={c['text']!r}: expected {len(c['ids'])} tokens, got {got}"
            )

    def test_encode_ids_match_golden_hello_world(self):
        # 'hello' + '▁world' merge via 4+5 BPE merges -> [336, 341]
        assert encode("hello world", BPE_TOK) == [336, 341]

    def test_encode_ids_match_golden_cjk_byte_fallback(self):
        # 你好 -> 6 byte-fallback tokens (each CJK char = 3 UTF-8 bytes)
        assert encode("你好", BPE_TOK) == [305, 266, 237, 306, 242, 266]

    def test_encode_ids_match_golden_added_token_split(self):
        # <start_of_image> (added token id 349) split out first, then 'caption'
        # BPE'd char-by-char (no merges apply) -> [349, 6,4,19,23,12,18,17]
        assert encode("<start_of_image>caption", BPE_TOK) == [
            349,
            6,
            4,
            19,
            23,
            12,
            18,
            17,
        ]

    def test_empty_text_zero_tokens(self):
        assert count_tokens("", BPE_TOK) == 0
        assert encode("", BPE_TOK) == []


class TestFallback:
    """Unsupported layouts (Qwen GPT-4 ByteLevel \\p{L}\\p{N}\\p{M} regex;
    SentencePiece .model protobuf; missing file; non-JSON) fall back to a
    conservative len(text) estimate — safe (over-count) for a budget guard."""

    def test_qwen_bytelevel_falls_back_to_len(self):
        # Qwen pre_tokenizer is Split(Regex) + ByteLevel -> unsupported in stdlib
        assert count_tokens("Hello world", QWEN_TOK) == len("Hello world")

    def test_encode_raises_on_qwen_unsupported(self):
        with pytest.raises(TokenizeUnsupported):
            encode("hi", QWEN_TOK)

    def test_missing_file_falls_back_to_len(self):
        assert count_tokens("hi", "/no/such/tokenizer.json") == len("hi")

    def test_non_json_falls_back_to_len(self, tmp_path):
        f = tmp_path / "tok.json"
        f.write_text("not json {")
        assert count_tokens("hi", str(f)) == len("hi")

    def test_sentencepiece_model_falls_back_to_len(self, tmp_path):
        # .model (protobuf) is not JSON -> _parse returns None -> fallback
        f = tmp_path / "tokenizer.model"
        f.write_text("binary-ish content")
        assert count_tokens("hi", str(f)) == len("hi")
